const dicts: Record<Lang, Partial<Strings>> = { en, ru };

export function strings(lang: Lang): Strings {
  if (lang === 'en') return en;
  // shallow merge with English fallback; nested records merged one level deep
  const d = dicts[lang];
  const out = { ...en } as Record<string, unknown>;
  for (const [k, v] of Object.entries(d)) {
    const base = (en as Record<string, unknown>)[k];
    out[k] = v && typeof v === 'object' && !Array.isArray(v) && base && typeof base === 'object' ? { ...(base as object), ...(v as object) } : v;
  }
  return out as Strings;
}

export function fmt(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

export function money(n: number) {
  const sign = n < 0 ? '−' : '';
  return `${sign}₹${Math.abs(Math.round(n)).toLocaleString('en-IN')}`;
}

export function meters(m: number) {
  if (m >= 1000) return `${(m / 1000).toFixed(1)} km`;
  return `${Math.max(0, Math.round(m / 10) * 10)} m`;
}
